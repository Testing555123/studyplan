import { defineConfig, devices } from '@playwright/test'

/**
 * Playwright 端到端测试配置。
 *
 * ── E2E 与单测的分工（本阶段最值得记住的一件事）──
 *
 *   单元测试（阶段 3-7 写的 Jest）：**快、稳、覆盖逻辑分支**。
 *     它用替身把数据库和网络都换掉了，所以能在几秒内跑几百个用例。
 *     但它证明不了"整个系统能跑"—— 因为它跑的根本不是真系统。
 *
 *   E2E（这个文件）：**慢、脆、但覆盖真实链路**。
 *     它开一个真实浏览器，点真实按钮，发真实请求，写真实数据库。
 *     所以它能发现单测永远发现不了的问题：CORS 配错、
 *     前端字段名和后端对不上、Cookie 没带上、路由守卫把正常用户拦了。
 *
 * **两者不是替代关系，是互补关系。** 单测告诉你"逻辑对不对"，
 * E2E 告诉你"连起来能不能用"。
 *
 * ── 一个纪律：E2E 不追求覆盖率 ──
 * 它只覆盖**关键路径**（能赚钱 / 能交付价值的那几条）。
 * 本项目就一条：新用户能注册、发帖、互动。
 * 给 E2E 追求覆盖率会让测试套件变得又慢又脆，最后没人愿意跑。
 */
export default defineConfig({
  testDir: './e2e',

  /** 单条用例上限。E2E 涉及真实网络与渲染，给宽一点 */
  timeout: 60_000,

  /**
   * 关掉并行。
   *
   * 因为这些用例之间有**真实的状态依赖**：注册的账号会被后面的
   * 发帖、评论用例复用。并行执行时它们会互相干扰 ——
   * 而这种失败是偶发的，最消耗排查时间。
   *
   * > 能并行的才并行。有共享状态的测试串行跑更省心。
   */
  fullyParallel: false,
  workers: 1,

  /** 失败重试。设 0 是因为我们要看到真实的失败，而不是被重试掩盖的偶发 */
  retries: 0,

  reporter: [['list']],

  use: {
    /**
     * 被测站点的地址。
     *
     * 用环境变量覆盖，于是同一套测试既能跑本地也能跑线上 ——
     * 这正是本阶段"部署"和"测试"能结合的地方：
     * 上线之后把 E2E_BASE_URL 指向线上地址，就能验证部署是否真的成功。
     */
    baseURL: process.env.E2E_BASE_URL ?? 'http://localhost:3001',

    /** 失败时保留追踪文件，可以回放整个操作过程（排查偶发问题的利器） */
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    locale: 'zh-CN',
    timezoneId: 'Asia/Shanghai',

    /**
     * 可选代理。用 `E2E_PROXY=http://127.0.0.1:7897` 启用。
     *
     * 为什么需要它？当被测环境在境外、而本机网络访问受限时，
     * **真实浏览器同样连不上**，整套 E2E 会全部失败在"页面打不开"这一步 ——
     * 那种失败看起来像应用坏了，实际是链路问题，最容易误判。
     * （本项目实测：`*.vercel.app` 既有 DNS 污染，又有 TLS SNI 阻断。）
     *
     * 只在设置了该环境变量时才生效，因此不影响本地跑测。
     */
    ...(process.env.E2E_PROXY
      ? {
          proxy: { server: process.env.E2E_PROXY },
          // 本地代理若开了 TLS 拦截，证书链会变成自签，需要放宽校验
          ignoreHTTPSErrors: true,
        }
      : {}),
  },

  projects: [
    {
      name: 'chromium',
      use: { ...devices['Desktop Chrome'] },
    },
  ],
})
