/**
 * 应用启动时恢复登录态。
 *
 * ── 为什么这件事要放在插件里，而不是某个页面的 onMounted？ ──
 * 因为它是**全局的启动逻辑**：无论用户从哪个页面进来，
 * 界面上的登录态都应该立刻是对的。
 *
 * 如果写在页头组件的 onMounted 里，也能"碰巧"工作，
 * 但那是"因为这个组件恰好在每个页面上"这种巧合。
 * 插件表达的是"这件事属于应用启动流程" —— 意图更明确，
 * 而且将来换掉页头也不会连带弄坏登录态恢复。
 *
 * ── 为什么文件名带 `.client` 后缀？ ──
 * Nuxt 约定：带 `.client` 的插件**只在浏览器执行**。
 * 这正好符合需求 —— 服务端既拿不到用户内存里的 Token，
 * 也不该去动用用户的 Cookie（见 useAuth.ts 里 restore 的注释）。
 *
 * 用文件名强制约束，比在代码里写 `if (import.meta.client)` 更不容易被误删。
 */
export default defineNuxtPlugin(() => {
  const auth = useAuth()

  /**
   * 刻意不 await：让页面先渲染出来，登录态恢复在后台进行。
   * 阻塞启动会让首屏白屏时间变长，而用户看到短暂的头像占位
   * 远比"页面卡住不动"要好。
   */
  void auth.restore()
})
