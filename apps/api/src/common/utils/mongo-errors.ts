/**
 * MongoDB 错误码工具。
 *
 * ── 为什么把它从 users.service.ts 提到这里？ ──
 * 阶段 5 写注册时，这个判断只服务于"邮箱不能重复"。
 * 阶段 6 的点赞模块需要**完全相同的判断** ——
 * "同一个人对同一篇帖子只能赞一次"靠的也是唯一索引。
 *
 * 第二个使用者出现，就是该抽取的信号。（和作者快照 Schema 同一条原则。）
 */
export function isDuplicateKeyError(error: unknown): boolean {
  return (
    typeof error === 'object' &&
    error !== null &&
    'code' in error &&
    (error as { code?: number }).code === 11000
  )
}

/**
 * 关于"为什么用错误码而不是先查一次再插入"
 * ────────────────────────────────────────────────────────
 *
 * 下面这种写法看起来更"安全"，其实有并发漏洞：
 *
 * ```ts
 * const exists = await model.findOne({ email })
 * if (exists) throw new ConflictException('已存在')
 * await model.create({ email })     // ← 两个并发请求可能同时走到这里
 * ```
 *
 * "查"和"插"之间有一个时间窗口。两个请求可以**同时**查到
 * "不存在"，然后都去插入 —— 最终要么产生重复数据，
 * 要么其中一个抛出数据库层的错误（那会被当成 500）。
 *
 * 正确姿势是：**直接插，让数据库的唯一索引来裁决**，
 * 然后把数据库错误翻译成业务错误。
 *
 * 唯一索引是数据库层面保证的，任何并发都绕不过去。
 * 应用层的检查只能用来"给出更友好的提示"，不能用来保证正确性。
 *
 * > 一条通用原则：**正确性交给有约束能力的那一层去做。**
 * > 并发场景下，能提供约束的只有数据库。
 */
